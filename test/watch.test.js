'use strict';
const assert = require('assert');
const { makeDeviceWatch, windowNotice } = require('../lib/watch');
const w = makeDeviceWatch({ minutes: 5 });
assert.strictEqual(w.check(1000), '', 'never seen: nothing to report (server just restarted)');
assert.strictEqual(w.seen(1000), '');
assert.strictEqual(w.check(1000 + 299), '', 'quiet for less than 5 minutes');
const down = w.check(1000 + 300);
assert(down.includes('ESP32') && down.includes('5 นาที'), down);
assert.strictEqual(w.check(1000 + 900), '', 'only one alert per outage');
assert.strictEqual(w.state(2000).down, true);
const up = w.seen(1000 + 1200);
assert(up.includes('กลับมาออนไลน์') && up.includes('20 นาที'), up);
assert.strictEqual(w.seen(1000 + 1205), '', 'no repeat');
assert.strictEqual(w.check(1000 + 1210), '');
assert.strictEqual(makeDeviceWatch({ minutes: 0 }).check(1e9), '', '0 = off');
assert.strictEqual(windowNotice(null, true), '', 'first evaluation says nothing');
assert.strictEqual(windowNotice(true, true), '');
assert(windowNotice(true, false).includes('หมดวันเทรด'));
assert(windowNotice(false, true).includes('เริ่มวันเทรดใหม่'));
console.log('watch tests ok');
